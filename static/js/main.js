const schwabResult = urlParams.get('schwab');
const errorMessage = urlParams.get('message');
if (schwabResult === 'success') {
    alert('Successfully connected to Charles Schwab!');
    window.history.replaceState({}, document.title, window.location.pathname);
} else if (schwabResult === 'error') {
    alert('Schwab Connection Failed: ' + (errorMessage || 'Unknown error'));
    window.history.replaceState({}, document.title, window.location.pathname);
}

// Auth Lifecycle Observer
onAuthStateChanged(auth, (user) => {
    if (user) {
        document.getElementById('user-display-email').innerText = user.email;
        showView('view-main');
        checkSchwabStatus();
    } else {
        showView('view-login');
        // Clear the API output on logout so the next user doesn't see it
        document.getElementById('api-output').innerText = "";
        const outputPre = document.getElementById('schwab-output');
        if (outputPre) {
            outputPre.innerText = "";
            outputPre.style.display = "none";
        }
    }
});

// Event Listeners for static buttons
document.getElementById('btn-login').addEventListener('click', async () => {
    const email = document.getElementById('email').value;
    const password = document.getElementById('password').value;
    document.getElementById('login-error').innerText = "";

    try {
        await signInWithEmailAndPassword(auth, email, password);
    } catch (error) {
        document.getElementById('login-error').innerText = "Authentication failed: " + error.message;
    }
});

document.getElementById('btn-logout').addEventListener('click', async () => {
    try { await signOut(auth); }
    catch (error) { console.error("Logout failed", error); }
});

document.getElementById('btn-fetch-hello').addEventListener('click', async () => {
    const user = auth.currentUser;
    if (!user) return;

    // 1. Get the secure token generated by Firebase
    const token = await user.getIdToken();

    // 2. Send it to app.py
    const response = await fetch('/api/hello', {
        headers: { 'Authorization': `Bearer ${token}` }
    });

    const data = await response.json();

    // 3. Display the response from Python
    if (response.ok) {
        document.getElementById('api-output').innerText = data.message;
    } else {
        document.getElementById('api-output').innerText = "Error: " + data.error;
    }
});

async function checkSchwabStatus() {
    const user = auth.currentUser;
    if (!user) return;

    const statusText = document.getElementById('schwab-status-text');
    const actionsDiv = document.getElementById('schwab-actions');
    statusText.innerText = "Checking...";
    statusText.style.color = "gray";

    try {
        const token = await user.getIdToken();
        const response = await fetch('/api/schwab/status', {
            headers: { 'Authorization': `Bearer ${token}` }
        });
        const data = await response.json();

        if (data.connected) {
            statusText.innerText = "Connected";
            statusText.style.color = "green";
            actionsDiv.innerHTML = `
                <button id="btn-fetch-accounts">Fetch Account Details</button>
                <button id="btn-disconnect" style="background-color: #ffcccc; color: #cc0000; border: 1px solid #cc0000; margin-left: 10px;">Disconnect</button>
            `;
            document.getElementById('btn-fetch-accounts').addEventListener('click', fetchSchwabAccounts);
            document.getElementById('btn-disconnect').addEventListener('click', disconnectSchwab);
        } else {
            statusText.innerText = "Disconnected";
            statusText.style.color = "red";
            actionsDiv.innerHTML = `<button id="btn-connect">Connect Schwab</button>`;
            document.getElementById('btn-connect').addEventListener('click', connectSchwab);
        }
    } catch (error) {
        console.error("Error checking Schwab status:", error);
        statusText.innerText = "Error checking status";
        statusText.style.color = "red";
    }
}

async function connectSchwab() {
    const user = auth.currentUser;
    if (!user) return;
    try {
        const token = await user.getIdToken();
        const response = await fetch('/api/auth/schwab', {
            method: 'POST',
            headers: { 'Authorization': `Bearer ${token}` }
        });
        const data = await response.json();
        if (response.ok && data.url) {
            window.location.href = data.url;
        } else {
            alert('Failed to initiate Schwab connection: ' + (data.error || 'Unknown error'));
        }
    } catch (error) {
        console.error("Failed to connect Schwab:", error);
    }
}

async function fetchSchwabAccounts() {
    const user = auth.currentUser;
    if (!user) return;
    const outputPre = document.getElementById('schwab-output');
    outputPre.style.display = "block";
    outputPre.innerText = "Fetching accounts...";
    try {
        const token = await user.getIdToken();
        const response = await fetch('/api/schwab/accounts', {
            headers: { 'Authorization': `Bearer ${token}` }
        });
        const data = await response.json();
        if (response.ok) {
            outputPre.innerText = JSON.stringify(data, null, 2);
        } else {
            outputPre.innerText = "Error: " + (data.error || 'Failed to fetch');
        }
    } catch (error) {
        outputPre.innerText = "Error: " + error.message;
    }
}

async function disconnectSchwab() {
    if (!confirm("Are you sure you want to disconnect your Schwab account? This will revoke access token storage.")) return;
    const user = auth.currentUser;
    if (!user) return;
    try {
        const token = await user.getIdToken();
        const response = await fetch('/api/schwab/disconnect', {
            method: 'POST',
            headers: { 'Authorization': `Bearer ${token}` }
        });
        if (response.ok) {
            const outputPre = document.getElementById('schwab-output');
            outputPre.innerText = "";
            outputPre.style.display = "none";
            checkSchwabStatus();
        } else {
            alert("Failed to disconnect");
        }
    } catch (error) {
        console.error("Disconnect failed", error);
    }
}
